CREATE TABLE dealer_customers (
    id VARCHAR(128) PRIMARY KEY,
    profile TEXT NOT NULL,
    opted_out BOOLEAN DEFAULT FALSE NOT NULL
);
CREATE TABLE dealer_identities (
    channel VARCHAR(32) NOT NULL,
    account_id VARCHAR(128) NOT NULL,
    external_id VARCHAR(512) NOT NULL,
    customer_id VARCHAR(128) NOT NULL REFERENCES dealer_customers(id),
    verified BOOLEAN NOT NULL,
    consent BOOLEAN NOT NULL,
    outbound_allowed BOOLEAN NOT NULL,
    last_inbound_at BIGINT,
    PRIMARY KEY (channel, account_id, external_id),
    UNIQUE (customer_id, channel)
);
CREATE TABLE dealer_conversations (
    customer_id VARCHAR(128) PRIMARY KEY REFERENCES dealer_customers(id),
    campaign_id VARCHAR(128),
    workflow TEXT NOT NULL,
    summary TEXT NOT NULL,
    last_activity_at BIGINT NOT NULL
);
CREATE TABLE dealer_messages (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id VARCHAR(128) UNIQUE NOT NULL,
    customer_id VARCHAR(128) NOT NULL REFERENCES dealer_customers(id),
    direction VARCHAR(16) NOT NULL,
    channel VARCHAR(32) NOT NULL,
    account_id VARCHAR(128) NOT NULL,
    external_id VARCHAR(512),
    content TEXT NOT NULL,
    delivery_status VARCHAR(32) NOT NULL,
    occurred_at BIGINT NOT NULL,
    UNIQUE (channel, account_id, direction, external_id)
);
CREATE INDEX ix_dealer_messages_customer ON dealer_messages(customer_id, sequence);
CREATE TABLE dealer_executions (
    id VARCHAR(128) PRIMARY KEY,
    customer_id VARCHAR(128) NOT NULL REFERENCES dealer_customers(id),
    campaign_id VARCHAR(128) NOT NULL,
    configuration TEXT NOT NULL,
    status VARCHAR(32) NOT NULL,
    current_channel VARCHAR(32),
    next_attempt_at BIGINT NOT NULL,
    last_contact_at BIGINT,
    failure_count INTEGER DEFAULT 0 NOT NULL,
    UNIQUE (customer_id, campaign_id)
);
CREATE TABLE dealer_attempts (
    id VARCHAR(128) PRIMARY KEY,
    execution_id VARCHAR(128) NOT NULL REFERENCES dealer_executions(id),
    channel VARCHAR(32) NOT NULL,
    attempt_number INTEGER NOT NULL,
    script_key VARCHAR(128) NOT NULL,
    status VARCHAR(32) NOT NULL,
    message_id VARCHAR(128) NOT NULL,
    attempted_at BIGINT NOT NULL,
    UNIQUE (execution_id, channel, attempt_number)
);
CREATE TABLE dealer_channel_progress (
    execution_id VARCHAR(128) NOT NULL REFERENCES dealer_executions(id),
    channel VARCHAR(32) NOT NULL,
    reason VARCHAR(32) NOT NULL,
    PRIMARY KEY (execution_id, channel)
);
CREATE TABLE dealer_slots (
    id VARCHAR(128) PRIMARY KEY,
    starts_at BIGINT NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0)
);
CREATE TABLE dealer_appointments (
    id VARCHAR(128) PRIMARY KEY,
    customer_id VARCHAR(128) NOT NULL REFERENCES dealer_customers(id),
    service_id VARCHAR(128) NOT NULL,
    slot_id VARCHAR(128) NOT NULL REFERENCES dealer_slots(id),
    status VARCHAR(32) NOT NULL,
    updated_at BIGINT NOT NULL
);
CREATE INDEX ix_dealer_appointments_slot ON dealer_appointments(slot_id, status);
CREATE TABLE dealer_events (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id VARCHAR(128) NOT NULL,
    execution_id VARCHAR(128),
    event_type VARCHAR(64) NOT NULL,
    occurred_at BIGINT NOT NULL
);
